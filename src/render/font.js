// A 3×5 pixel font for in-canvas labels (floating "+$2" text).
const GLYPHS = {
  '0': '111101101101111', '1': '010110010010111', '2': '111001111100111', '3': '111001111001111', '4': '101101111001001',
  '5': '111100111001111', '6': '111100111101111', '7': '111001001001001', '8': '111101111101111', '9': '111101111001111',
  'A': '010101111101101', 'B': '110101110101110', 'C': '111100100100111', 'D': '110101101101110', 'E': '111100110100111',
  'F': '111100110100100', 'G': '111100101101111', 'H': '101101111101101', 'I': '111010010010111', 'J': '001001001101111',
  'K': '101101110101101', 'L': '100100100100111', 'M': '101111111101101', 'N': '110101101101101', 'O': '111101101101111',
  'P': '111101111100100', 'Q': '111101101111001', 'R': '111101110101101', 'S': '111100111001111', 'T': '111010010010010',
  'U': '101101101101111', 'V': '101101101101010', 'W': '101101111111101', 'X': '101101010101101', 'Y': '101101010010010',
  'Z': '111001010100111', '$': '011110111011110', '+': '000010111010000', '-': '000000111000000', '.': '000000000000010',
  ':': '000010000010000', ' ': '000000000000000', '!': '010010010000010', '%': '101001010100101', '/': '001001010100100',
  "'": '010010000000000', ',': '000000000010100', '(': '010100100100010', ')': '010001001001010',
};
export function drawText(ctx, text, x, y, color, scale = 2, outline = '#000') {
  const s = String(text).toUpperCase();
  let cx = x;
  for (const ch of s) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let i = 0; i < 15; i++) if (g[i] === '1') {
      const px = cx + (i % 3) * scale, py = y + Math.floor(i / 3) * scale;
      if (outline) { ctx.fillStyle = outline; ctx.fillRect(px - 1, py - 1, scale + 2, scale + 2); }
    }
    cx += 4 * scale;
  }
  cx = x;
  for (const ch of s) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    ctx.fillStyle = color;
    for (let i = 0; i < 15; i++) if (g[i] === '1') ctx.fillRect(cx + (i % 3) * scale, y + Math.floor(i / 3) * scale, scale, scale);
    cx += 4 * scale;
  }
}
export const textWidth = (text, scale = 2) => String(text).length * 4 * scale - scale;
